"""Deterministic, read-only repository source indexing.

The scanner is deliberately conservative: it reads only UTF-8 text files that
look like source or documentation, never executes repository code, never follows
symlinks, and never writes during discovery or search.  Persistence is an
explicit offline operation through :meth:`RepositoryIndex.save`.
"""

